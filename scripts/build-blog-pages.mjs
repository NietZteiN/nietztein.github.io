			<div class="article-meta">${meta.date ? '<time datetime="' + meta.date + '">' + new Date(meta.date + 'T00:00:00Z').toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' }) + '</time>' : ''}<span>${minutes} min read</span></div>
