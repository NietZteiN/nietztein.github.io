	const cjk = (rendered.text.match(/[\u3040-\u30ff\u3400-\u9fff]/g) || []).length;
	const words = (rendered.text.replace(/[\u3040-\u30ff\u3400-\u9fff]/g, ' ').match(/\S+/g) || []).length;
	const minutes = Math.max(1, Math.ceil(words / 220 + cjk / 500));
	const headings = rendered.headings.filter((heading) => heading.level <= 3);
	const contents = headings.length >= 2 && minutes >= 4 ? '<details class="article-contents"><summary>On this page</summary><nav aria-label="Article contents"><ol>' + headings.map((heading) => '<li><a href="#' + heading.id + '">' + escapeHtml(heading.text) + '</a></li>').join('') + '</ol></nav></details>' : '';
