// Fixture-based publishing boundary, escaping, determinism and cleanup checks.
// Does not require the repository's generated outputs to be current: the index
// workflow can be generating them concurrently with the normal Check workflow.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { buildPages, PAGE_MARKER } from './build-blog-pages.mjs';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'blog-pages-test-'));
const git = (...args) => execFileSync('git', args, { cwd: root, stdio: 'pipe', windowsHide: true });
const file = (...parts) => path.join(root, ...parts);
const read = (...parts) => fs.readFileSync(file(...parts), 'utf8');
function write(relative, text) { fs.mkdirSync(path.dirname(file(relative)), { recursive: true }); fs.writeFileSync(file(relative), text); }
function post(name, title, body, summary = 'A < B & "quoted" text.', kind = '') {
	write('blog/posts/' + name, '---\ntitle: ' + title + '\nsummary: ' + summary + '\ntags: [language, testing]\n' + (kind ? 'kind: ' + kind + '\n' : '') + '---\n\n' + body + '\n');
}

try {
	git('init', '--quiet');
	post('2026-01-01-first.md', 'First & "Quoted" title', '# First & "Quoted" title\n\n## Repeat\n\n' + 'Readable language and code. '.repeat(250) + '\n\n<!-- PRIVATE_NOTE\n- hidden list content\n-->\n\nVisible after comment.\n\n## Repeat\n\n## Repeat 2\n\n' +
		'[Jump](#repeat) [Internal](https://nietztein.github.io/#/post/second) [Legacy](#/blog?tag=language) [File](assets/documents/latentland.pdf)\n\n' +
		'[Unsafe](javascript:alert(1)) [Encoded](jav&#x61;script:alert(1)) [Colon](javascript&colon;alert(1)) [Data](data:text/html,unsafe)\n\n' +
		'![Safe image](/assets/img/og/card.png) ![Bad image](javascript:alert(1))\n\n' +
		'Inline `<!-- literal inline -->`.\n\n```html\n<!-- literal fenced -->\n<script>code sample</script>\n```\n\n' +
		'<script>RAW_SCRIPT_SECRET</script>\n\n<img src="x" onerror="RAW_EVENT_SECRET">\n\n' +
		'| Column | Value |\n| --- | --- |\n| A | B |');
	post('2026-01-02-second.md', 'Second', 'A second public post.');
	post('2026-01-03-injection.md', '</script><script>alert("metadata")</script>', 'Safe public body.');
	post('2026-01-04-short-note.md', 'Fixture short note', 'A brief authored fixture.', 'A brief note summary.', 'note');
	post('2026-01-04-private.md', 'Private', 'UNTRACKED_SECRET');
	post('nested/2026-01-05-nested.md', 'Nested', 'NESTED_SECRET');
	write('blog/drafts/private.md', 'DRAFT_SECRET');
	git('add', '--', 'blog/posts/2026-01-01-first.md', 'blog/posts/2026-01-02-second.md', 'blog/posts/2026-01-03-injection.md', 'blog/posts/2026-01-04-short-note.md', 'blog/posts/nested/2026-01-05-nested.md', 'blog/drafts/private.md');
	write('writing/handmade/index.html', '<h1>Keep this manual page</h1>');
	write('writing/notes.txt', 'Keep this unrelated file');
	const result = buildPages({ root });
	assert.equal(result.count, 4);
	assert.equal(result.ok, true);
	const first = read('writing/first/index.html');
	assert.match(first, /^<!-- Generated by scripts\/build-blog-pages\.mjs/);
	assert.match(first, /<link rel="canonical" href="https:\/\/nietztein\.github\.io\/writing\/first\/">/);
	assert.match(first, /<meta property="og:title" content="First &amp; &quot;Quoted&quot; title">/);
	assert.match(first, /<meta name="twitter:description" content="A &lt; B &amp; &quot;quoted&quot; text\.">/);
	assert.match(first, /<time datetime="2026-01-01">January 1, 2026<\/time>/);
	assert.match(first, /data-article-slug="first"/);
	assert.match(first, /data-post-kind="article"/);
	assert.ok(first.indexOf('src="../../assets/js/saved-store.js"') < first.indexOf('src="../../assets/js/saved-controls.js"'), 'saved store loads before its controls');
	assert.match(first, /class="article-body">/);
	assert.match(first, /Visible after comment\./);
	assert.doesNotMatch(first, /PRIVATE_NOTE|RAW_SCRIPT_SECRET|RAW_EVENT_SECRET|onerror=/);
	assert.match(first, /&lt;!-- literal inline --&gt;/);
	assert.match(first, /&lt;!-- literal fenced --&gt;/);
	assert.match(first, /&lt;script&gt;code sample&lt;\/script&gt;/);
	assert.match(first, /href="\/writing\/second\/"/);
	assert.match(first, /href="\/#\/blog\?tag=language"/);
	assert.match(first, /href="\/assets\/documents\/latentland\.pdf"/);
	assert.doesNotMatch(first, /href="(?:javascript|data):/i);
	assert.match(first, /src="\/assets\/img\/og\/card\.png"/);
	assert.equal((first.match(/<img /g) || []).length, 1);
	const ids = Array.from(first.matchAll(/<h2 id="([^"]+)"/g), (match) => match[1]);
	assert.equal(ids.length, 3);
	assert.equal(new Set(ids).size, 3);
	assert.match(first, /href="#post-first-repeat"/);
	assert.match(first, /<div class="article-table"><table>/);
	assert.match(first, /assets\/js\/reader-libs\.js/);
	assert.doesNotMatch(first, /(?:src|href)="[^"\n]*desk\/vendor\/(?:katex|highlight)\//);
	const injection = read('writing/injection/index.html');
	assert.doesNotMatch(injection, /<script>alert\("metadata"\)<\/script>/);
	assert.match(injection, /\\u003c\/script\\u003e/);
	const note = read('writing/short-note/index.html');
	assert.match(note, /<meta property="article:section" content="Short notes">/);
	assert.match(note, /"articleSection":"Short notes"/);
	assert.match(note, /data-post-kind="note"/);
	assert.match(note, /href="\/#\/blog\?format=note">Short note<\/a>/);
	assert.match(note, /A brief authored fixture\./);
	const feed = read('feed.xml');
	assert.equal((feed.match(/<item>/g) || []).length, 4);
	assert.equal((feed.match(/<category>Short notes<\/category>/g) || []).length, 1);
	assert.match(feed, /<title>First &amp; &quot;Quoted&quot; title<\/title>/);
	assert.match(feed, /<description>A &lt; B &amp; &quot;quoted&quot; text\.<\/description>/);
	assert.match(feed, /<guid isPermaLink="true">https:\/\/nietztein\.github\.io\/writing\/first\/<\/guid>/);
	assert.match(feed, /<pubDate>Thu, 01 Jan 2026 00:00:00 GMT<\/pubDate>/);
	assert.doesNotMatch(feed + read('sitemap.xml'), /private|nested|draft|PRIVATE|SECRET/);
	assert.equal((read('sitemap.xml').match(/<loc>/g) || []).length, 5);
	assert.equal(read('writing/handmade/index.html'), '<h1>Keep this manual page</h1>');
	assert.equal(read('writing/notes.txt'), 'Keep this unrelated file');
	assert.equal(fs.existsSync(file('writing/private/index.html')), false);
	assert.equal(fs.existsSync(file('writing/nested/index.html')), false);
	const modified = fs.statSync(file('feed.xml')).mtimeMs;
	assert.deepEqual(buildPages({ root }).differences, []);
	assert.equal(fs.statSync(file('feed.xml')).mtimeMs, modified, 'idempotent builds do not rewrite outputs');
	assert.equal(buildPages({ root, check: true }).ok, true);
	write('feed.xml', 'outdated feed');
	const check = buildPages({ root, check: true });
	assert.equal(check.ok, false);
	assert.ok(check.differences.includes('feed.xml'));
	assert.equal(read('feed.xml'), 'outdated feed', '--check is read-only');
	buildPages({ root });
	write('writing/second/keep.txt', 'Keep the neighbor');
	write('writing/stale-empty/index.html', PAGE_MARKER + '\nOld generated content.');
	git('rm', '--cached', '--', 'blog/posts/2026-01-02-second.md');
	assert.equal(buildPages({ root, check: true }).ok, false);
	assert.ok(fs.existsSync(file('writing/second/index.html')), 'check does not remove stale outputs');
	buildPages({ root });
	assert.equal(fs.existsSync(file('writing/second/index.html')), false);
	assert.equal(read('writing/second/keep.txt'), 'Keep the neighbor');
	assert.equal(fs.existsSync(file('writing/stale-empty')), false);
	assert.equal(read('writing/handmade/index.html'), '<h1>Keep this manual page</h1>');
	post('2026-01-06-handmade.md', 'Manual collision', 'Do not overwrite the existing handmade page.');
	git('add', '--', 'blog/posts/2026-01-06-handmade.md');
	assert.throws(() => buildPages({ root }), /unowned article/);
	assert.equal(read('writing/handmade/index.html'), '<h1>Keep this manual page</h1>');
	git('rm', '--cached', '--', 'blog/posts/2026-01-06-handmade.md');
	write('outside/index.html', 'Outside content');
	fs.symlinkSync(file('outside'), file('writing/escape'), process.platform === 'win32' ? 'junction' : 'dir');
	post('2026-01-07-escape.md', 'Symlink collision', 'Do not write outside writing/.');
	git('add', '--', 'blog/posts/2026-01-07-escape.md');
	assert.throws(() => buildPages({ root }), /real directory/);
	assert.equal(read('outside/index.html'), 'Outside content');
	console.log('Blog pages: publishing boundary, metadata/URL escaping, comments/code, stable RSS, idempotence, --check and owned cleanup passed');
} finally {
	if (path.dirname(path.resolve(root)) !== path.resolve(os.tmpdir())) throw new Error('Unexpected cleanup target');
	fs.rmSync(root, { recursive: true, force: true });
}
