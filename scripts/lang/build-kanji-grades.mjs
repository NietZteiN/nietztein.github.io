// Builds misc/_lang/kanji-grades.js: the 2,136 joyo kanji in school order with
// their stroke counts, for a page that needs only "the kanji known by grade N".
//
//   node scripts/lang/build-kanji-grades.mjs
//
// Source: KANJIDIC2 (EDRDG, CC BY-SA 4.0): the grade and the first stroke count.

import { json, writeDataFile, isKanjiCp } from './lib.mjs';
import { loadKanjidic2, isJoyoGrade, EDRDG_LICENCE_URL } from './edrdg.mjs';

const kd = await loadKanjidic2();
const joyo = kd.characters.filter((c) => isJoyoGrade(c.grade));
if (joyo.length !== 2136) throw new Error(`build-kanji-grades: KANJIDIC2 grades ${joyo.length} kanji as joyo, expected 2,136`);
// Grade, then stroke count, then code point.
joyo.sort((a, b) => a.grade - b.grade || a.strokes - b.strokes || a.literal.codePointAt(0) - b.literal.codePointAt(0));
for (const c of joyo) if ([...c.literal].length !== 1 || !isKanjiCp(c.literal.codePointAt(0)) || !(c.strokes >= 1)) throw new Error('build-kanji-grades: bad entry ' + c.literal);

const counts = {};
for (const c of joyo) counts[c.grade] = (counts[c.grade] || 0) + 1;

const meta = {
	sources: [{ ...kd.source, file: 'KANJIDIC2', version: kd.databaseVersion, created: kd.dateOfCreation }],
	licence: 'CC BY-SA 4.0 (' + EDRDG_LICENCE_URL + ')',
	credit:
		'Kanji grades and stroke counts from KANJIDIC2, the property of the Electronic Dictionary Research and Development Group, used in conformance with the Group\'s licence (CC BY-SA 4.0): https://www.edrdg.org/wiki/index.php/KANJIDIC_Project',
	kept: { kanji: joyo.length, grades: counts },
	dropped: ['Everything in KANJIDIC2 except the character, its grade and its first stroke count; all kanji that are not joyo.'],
	notes: {
		order: 'Grade, then stroke count, then code point.',
		grade: '1 to 6 are the years of primary school; 8 is the rest of the joyo set (KANJIDIC2 uses 8 for it).',
	},
};

const body =
	'{\n"meta":' +
	json(meta) +
	',\n"counts":' +
	json(counts) +
	',\n"k":[\n' +
	joyo.map((c) => json([c.literal, c.grade, c.strokes])).join(',\n') +
	'\n]\n}';

writeDataFile('kanji-grades.js', 'LANG_KANJI_GRADES', body, [
	'misc/_lang/kanji-grades.js: the 2,136 joyo kanji in school order, [kanji, grade, strokes] (KANJIDIC2; EDRDG, CC BY-SA 4.0).',
	'Generated by scripts/lang/build-kanji-grades.mjs. Do not edit: rebuild.',
	'Sources, licences and the credit a page must show: misc/_lang/LICENSES.md',
]);
console.log(`kanji ${joyo.length}; grades ${json(counts)}`);
