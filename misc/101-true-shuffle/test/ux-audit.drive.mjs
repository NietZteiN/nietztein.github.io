export default async function ({newPage, baseUrl, assert, outDir}) {
 for (const theme of ['dark','light']) for (const width of [1280,390]) {
  const page=await newPage({width,height:width===390?844:860,mobile:width===390,theme});
  await page.goto(baseUrl+'misc/101-true-shuffle/?demo=1#/songs');
  await page.waitFor('.ts-row');
  const id=await page.eval(()=>document.querySelector('.ts-row').dataset.id);
  await page.click('.ts-row .ts-c-more button:last-child');
  await page.eval(()=>{const b=[...document.querySelectorAll('[role="menuitem"]')].find(b=>b.textContent.includes('Trim and volume'));b.id='audit-trim';});
  await page.click('#audit-trim');
  assert.equal(await page.eval(()=>document.querySelector('.ts-modal button[type="submit"]').textContent),'Save');
  await page.eval(()=>{const f=document.querySelector('.ts-modal form'), inputs=f.querySelectorAll('input[type="text"]');inputs[1].id='audit-end'; const range=f.querySelector('input[type="range"]');range.value='50';range.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.type('#audit-end','2:00');
  await page.screenshot(outDir+`/shuffle-trim-${theme}-${width}.png`);
  await page.click('.ts-modal button[type="submit"]');
  await page.waitFor(()=>!document.querySelector('.ts-modal'));
  assert.equal(await page.eval(id=>window.__ts.pageCtx.songPref(id).end,id),120);
  assert.equal(await page.eval(id=>window.__ts.pageCtx.songPref(id).vol,id),50);
  await page.eval(()=>document.activeElement.blur());
  const before=await page.eval(()=>+document.getElementById('vol').value);
  await page.key('-');
  assert.equal(await page.eval(()=>+document.getElementById('vol').value),Math.max(0,before-10));
  await page.eval(()=>window.__ts.store.putTracks(Object.values(window.__ts.lib.tracks)));
  const backup=await page.eval(()=>window.__ts.store.exportAll());
  backup.tracks=backup.tracks.slice(0,2);backup.history=[];
  await page.eval(data=>{const ctx=window.__ts.pageCtx;window.auditReloads=0;return window.TrueShuffle.backup.confirm(data,'small-backup.json',{...ctx,reload:()=>{window.auditReloads++;},status:()=>{},exportAll:()=>{}});},backup);
  assert.equal(await page.eval(()=>document.activeElement.textContent),'Cancel');
  await page.screenshot(outDir+`/shuffle-backup-${theme}-${width}.png`);
  await page.key('Escape');
  assert.equal(await page.eval(()=>window.auditReloads),0);
  const initial=await page.eval(()=>window.__ts.store.usage());
  await page.eval(data=>{const ctx=window.__ts.pageCtx;return window.TrueShuffle.backup.confirm(data,'small-backup.json',{...ctx,reload:()=>{window.auditReloads++;},status:()=>{},exportAll:()=>{}});},backup);
  await page.eval(()=>{[...document.querySelectorAll('.ts-modal button')].find(b=>b.textContent==='Replace everything').id='audit-replace';});
  await page.click('#audit-replace');
  await page.waitFor(()=>window.auditReloads===1);
  assert.equal((await page.eval(()=>window.__ts.store.usage())).tracks,2);
  await page.eval(()=>{[...document.querySelectorAll('button')].find(b=>b.textContent==='Undo').id='audit-undo';});
  await page.click('#audit-undo');
  await page.waitFor(()=>window.auditReloads===2);
  assert.deepEqual(await page.eval(()=>window.__ts.store.usage()),initial);
  await page.eval(()=>{location.hash='#/mix';});
  await page.waitFor('[data-id^="mix-families-"]');
  await page.eval(()=>document.querySelector('[data-id^="mix-families-"]').focus());
  const focusId=await page.eval(()=>document.activeElement.dataset.id);
  await page.key('Enter');
  assert.equal(await page.eval(()=>document.activeElement.dataset.id),focusId);
  await page.eval(()=>{location.hash='#/fix?tab=unsure';});
  await page.waitFor('.ts-guesspicks .ts-pick span');
  const readings=await page.eval(()=>[...document.querySelectorAll('.ts-guesspicks')].map(g=>{const r=g.closest('.ts-row').getBoundingClientRect(),b=g.getBoundingClientRect();return {inside:b.left>=r.left&&b.right<=r.right&&b.bottom<=r.bottom,labels:[...g.querySelectorAll('button')].every(x=>x.textContent.trim().startsWith('By '))};}));
  assert.ok(readings.length>0);assert.ok(readings.every(x=>x.inside&&x.labels));
  await page.screenshot(outDir+`/shuffle-naming-${theme}-${width}.png`);
  await page._send('Emulation.setTimezoneOverride',{timezoneId:'America/Chicago'});
  await page.eval(()=>{Date.now=()=>Date.parse('2026-10-01T03:00:00Z');const ctx=window.__ts.pageCtx;const id=Object.keys(ctx.lib().tracks)[0];ctx.history().push({id,kind:'play',at:Date.parse('2026-10-01T01:00:00Z')},{id,kind:'play',at:Date.parse('2026-09-30T22:00:00Z')});location.hash='#/history';});
  await page.waitFor('.ts-histlist');
  assert.equal(await page.eval(()=>document.querySelectorAll('.ts-histlist').length),1);
  assert.equal(await page.eval(()=>document.querySelector('.ts-histlist').previousElementSibling.textContent),'Today');
  assert.ok(await page.eval(()=>document.getElementById('view').textContent.includes('September 2026')));
  assert.deepEqual(page.errors,[]);assert.deepEqual(page.externalHosts,[]);
  await page.close();
 }
}
